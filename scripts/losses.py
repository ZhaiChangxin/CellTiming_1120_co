def gaussian_nll(y, mu, log_var, reduction='mean'):
    """
    ????????? (Gaussian Negative Log-Likelihood)?
    ??????????????? mu ????? log_var?

    ??: NLL = 0.5 * (log(sigma^2) + (y - mu)^2 / sigma^2) + C
    """
    # ?? log_var ?????? (?????????)
    # log_var = torch.clamp(log_var, min=-10, max=10)

    sigma_2 = torch.exp(log_var)

    # loss term
    loss = 0.5 * (log_var + (y - mu) ** 2 / sigma_2)

    # ????? 0.5 * log(2?) ????????? (??????????????)
    loss = loss + 0.5 * np.log(2 * np.pi)

    if reduction == 'mean':
        return loss.mean()
    elif reduction == 'sum':
        return loss.sum()
    else:
        return loss


def kl_divergence(z_q, z_p):
    """
    ??????????? KL ??: KL(Q || P)

    Args:
        z_q: ?????? Q(z|x)???? tuple (mu_q, logvar_q)
        z_p: ???? P(z)???? tuple (mu_p, logvar_p)?
             ?? z_p ? None???? P(z) ??????? N(0, I)?
    """
    mu_q, logvar_q = z_q

    if z_p is None:
        # KL(N(mu, var) || N(0, 1))
        # ??: -0.5 * sum(1 + log(var) - mu^2 - var)
        # dim=1 ??? latent ????
        kld = -0.5 * torch.sum(1 + logvar_q - mu_q.pow(2) - logvar_q.exp(), dim=1)
    else:
        # KL(N(mu1, var1) || N(mu2, var2))
        mu_p, logvar_p = z_p

        # ??: 0.5 * sum(log(var2/var1) + (var1 + (mu1-mu2)^2)/var2 - 1)
        kld = 0.5 * torch.sum(
            logvar_p - logvar_q - 1 +
            (logvar_q.exp() + (mu_q - mu_p).pow(2)) / logvar_p.exp(),
            dim=1
        )

    return kld.mean()  # ? batch ???


